create extension if not exists pgcrypto;

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  client_code text not null unique,
  pc_name text not null,
  location text not null,
  client_type text not null default 'Studio PC',
  ip_address text,
  hostname text,
  agent_version text,
  runtime_type text,
  status text not null default 'unknown' check (status in ('online','offline','unknown')),
  notes text,
  agent_token_hash text not null,
  last_seen timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.client_metrics (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients(id) on delete cascade,
  recorded_at timestamptz not null default now(),
  cpu_usage numeric(5,2),
  ram_usage numeric(5,2),
  disk_usage numeric(5,2),
  onair_status text,
  onair_cpu numeric(7,2),
  onair_ram numeric(12,3)
);

create table if not exists public.client_containers (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients(id) on delete cascade,
  container_name text not null,
  image text,
  status text not null default 'exited',
  cpu_usage numeric(7,2),
  memory_usage numeric(12,2),
  restart_count integer not null default 0,
  updated_at timestamptz not null default now(),
  unique(client_id, container_name)
);

create table if not exists public.client_aircast_images (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients(id) on delete cascade,
  repository text,
  tag text,
  image text not null,
  version text,
  image_id text,
  size text,
  updated_at timestamptz not null default now(),
  unique(client_id, image_id, image)
);

create table if not exists public.client_events (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients(id) on delete cascade,
  event_type text not null,
  message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_client_metrics_client_time on public.client_metrics(client_id, recorded_at desc);
create index if not exists idx_client_events_client_time on public.client_events(client_id, created_at desc);
create index if not exists idx_clients_last_seen on public.clients(last_seen desc);

alter table public.clients enable row level security;
alter table public.client_metrics enable row level security;
alter table public.client_containers enable row level security;
alter table public.client_aircast_images enable row level security;
alter table public.client_events enable row level security;

